def setup() -> None:
    for k, v in DUMMY_ENV.items():
        os.environ.setdefault(k, v)
    os.environ["COLUMNS"] = "80"  # argparse help wrapping
    sys.path.insert(0, str(ROOT / "backend" / "src"))


def _app():
    from roracle.api.app import create_app

    return create_app()


def gen_openapi(app) -> str:
    return json.dumps(app.openapi(), indent=2, sort_keys=True) + "\n"


# ---------------------------------------------------------------- settings
def _comments() -> dict[str, str]:
    """field name -> inline code comment, for Settings and AliasConfig class bodies."""
    import roracle.config as cfg

    src = inspect.getsource(cfg)
    by_line: dict[int, str] = {}
    for t in tokenize.generate_tokens(io.StringIO(src).readline):
        if t.type == tokenize.COMMENT:
            by_line[t.start[0]] = t.string.lstrip("# ").strip()
    out: dict[str, str] = {}
    for node in ast.walk(ast.parse(src)):
        if isinstance(node, ast.ClassDef) and node.name in ("Settings", "AliasConfig"):
            for st in node.body:
                if isinstance(st, ast.AnnAssign) and isinstance(st.target, ast.Name):
                    c = [by_line[n] for n in range(st.lineno, st.end_lineno + 1) if n in by_line]
                    if c:
                        out[st.target.id] = " ".join(c)
    return out


def _cell(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ")


def _type(f) -> str:
    a = f.annotation
    return str(a).replace("typing.", "") if not isinstance(a, type) else a.__name__


def gen_settings() -> str:
    from pydantic_core import PydanticUndefined

    from roracle.config import Settings
    from roracle.runtime import KEYS

    com = _comments()
    rows = []
    for name in sorted(Settings.model_fields):
        f = Settings.model_fields[name]
        secret = any(w in name for w in SECRET_WORDS)
        if f.default is PydanticUndefined:
            default = "(required)"
        elif secret and f.default != "":
            default = "***"
        else:
            default = f"`{f.default!r}`"
        desc = f.description or com.get(name, "")
        rt = "yes" if name in KEYS else ""
        rows.append(
            f"| `ROR_{name.upper()}` | `{_cell(_type(f))}` | {_cell(default)} | {rt} | {_cell(desc)} |"
        )
    return (
        HEADER
        + "# Settings reference\n\n"
        + "Every setting is an environment variable with the `ROR_` prefix (`roracle.config.Settings`). "
        + '"Runtime" marks settings an admin can override at runtime (`roracle.runtime.SettingsIn`); '
        + "a stored override wins over the environment. Secrets are shown as `***`.\n\n"
        + "| Env var | Type | Default | Runtime | Description |\n|---|---|---|---|---|\n"
        + "\n".join(rows)
        + "\n"
    )


# ---------------------------------------------------------------- cli
class _Captured(Exception):
    def __init__(self, parser):
        self.parser = parser


def _cli_parser() -> argparse.ArgumentParser:
    from roracle import __main__ as m

    orig = argparse.ArgumentParser.parse_args

    def grab(self, *a, **k):
        raise _Captured(self)

    argparse.ArgumentParser.parse_args = grab  # type: ignore[method-assign]
    try:
        m.main(["api"])
    except _Captured as c:
        return c.parser
    finally:
        argparse.ArgumentParser.parse_args = orig  # type: ignore[method-assign]
    raise RuntimeError("parser not captured")


def _walk(p: argparse.ArgumentParser, name: str, out: list[str], depth: int) -> None:
    help_text = p.format_help().replace(str(ROOT), "<repo>").rstrip()
    out.append(f"{'#' * depth} `{name}`\n\n```text\n{help_text}\n```\n")
    for a in p._actions:
        if isinstance(a, argparse._SubParsersAction):
            for n in sorted(a.choices):
                _walk(a.choices[n], f"{name} {n}", out, min(depth + 1, 4))


def gen_cli() -> str:
    out: list[str] = []
    _walk(_cli_parser(), "roracle", out, 2)
    return (
        HEADER
        + "# CLI reference\n\n`python -m roracle <command>` (the container entrypoint is `roracle`).\n\n"
        + "\n".join(out)
    )


# ---------------------------------------------------------------- mcp
def _params(schema: dict) -> str:
    req = set(schema.get("required", []))
    rows = []
    for n, s in schema.get("properties", {}).items():
        s = {k: v for k, v in s.items() if k != "title"}
        rows.append(f"| `{n}` | {'yes' if n in req else 'no'} | `{_cell(json.dumps(s, sort_keys=True))}` |")
    return (
        "| Parameter | Required | Schema |\n|---|---|---|\n" + "\n".join(rows) if rows else "No parameters."
    )


def gen_mcp(app) -> str:
    from roracle.mcp.server import build_mcp

    m = build_mcp(app)

    async def collect():
        return (
            await m.list_tools(),
            await m.list_prompts(),
            await m.list_resources(),
            await m.list_resource_templates(),
        )

    tools, prompts, resources, templates = asyncio.run(collect())
    tools = sorted(tools, key=lambda t: t.name)
    missing = {t.name for t in tools} - set(GATES)
    if missing:
        raise SystemExit(f"GATES has no entry for new MCP tools: {sorted(missing)}")
    out = [
        HEADER + "# MCP tool reference\n",
        (
            f'{len(tools)} tools, mounted at `POST /mcp`. "Scope" is the PAT scope the tool enforces '
            "(`write` = `_need_write`; others need `read`). A call that passes authentication and argument validation is audited as `mcp.<tool>`; see the [MCP guide](mcp.md#audit).\n"
        ),
    ]
    for t in tools:
        fn = m._tool_manager.get_tool(t.name).fn
        scope = "write" if "_need_write(" in inspect.getsource(fn) else "read"
        gate, ev = GATES[t.name]
        out.append(
            f"## `{t.name}`\n\n{' '.join((t.description or '').split())}\n\n"
            f"- Scope: `{scope}`\n- Label gates: {gate} (`{ev}`)\n\n{_params(t.input_schema)}\n"
        )
    out.append("## Prompts\n")
    for p in sorted(prompts, key=lambda x: x.name):
        args = ", ".join(f"`{a.name}`{'' if a.required else ' (optional)'}" for a in p.arguments or [])
        out.append(f"- `{p.name}` ({args}): {p.description}")
    out.append("\n## Resources\n")
    rs = [(str(r.uri), r.mime_type, r.description) for r in resources]
    rs += [(t.uri_template, t.mime_type, t.description) for t in templates]
    for uri, mime, d in sorted(rs):
        out.append(f"- `{uri}` (`{mime}`): {d}")
    return "\n".join(out) + "\n"


def generate(dest: Path) -> None:
    setup()
    app = _app()
    dest.mkdir(parents=True, exist_ok=True)
    (dest / "openapi.json").write_text(gen_openapi(app))
    (dest / "settings.md").write_text(gen_settings())
    (dest / "cli.md").write_text(gen_cli())
    (dest / "mcp-tools.md").write_text(gen_mcp(app))


def drift(fresh: Path, committed: Path = OUT) -> list[str]:
    bad = []
    for f in FILES:
        p = committed / f
        if not p.exists() or p.read_text() != (fresh / f).read_text():
            bad.append(f)
    return bad


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="regenerate to a temp dir; exit 1 on drift")
    args = ap.parse_args(argv)
    if not args.check:
        generate(OUT)
        return 0
    with tempfile.TemporaryDirectory() as td:
        generate(Path(td))
        bad = drift(Path(td))
    if bad:
        print(f"reference drift: {', '.join(bad)} (run gen_reference.py)", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
